#!/usr/bin/env python3
"""Generate es-index/src/analysis/standard_tables.rs from Lucene's JFlex-generated scanner.

Source (Apache-2.0), at the pinned tag:
    gh api 'repos/apache/lucene/contents/lucene/core/src/java/org/apache/lucene/analysis/standard/StandardTokenizerImpl.java?ref=releases/lucene/10.5.1'
Usage: gen_standard_tokenizer_tables.py <StandardTokenizerImpl.java>
"""
import re, sys
from pathlib import Path

src = Path(sys.argv[1]).read_text()


def java_unescape(s):
    out, i = [], 0
    while i < len(s):
        c = s[i]
        if c != "\\":
            out.append(ord(c)); i += 1; continue
        n = s[i + 1]
        if n == "u":
            out.append(int(s[i + 2:i + 6], 16)); i += 6
        elif n in "01234567":
            m = re.match(r"[0-7]{1,3}", s[i + 1:])
            out.append(int(m.group(0), 8)); i += 1 + len(m.group(0))
        else:
            out.append(ord({"n": "\n", "t": "\t", "r": "\r", "b": "\b", "f": "\f"}.get(n, n))); i += 2
    return out


def packed(name):
    start = src.index(f"String {name}_PACKED_0 =")
    body = src[start:src.index('";\n', start) + 2]
    return java_unescape("".join(re.findall(r'"((?:[^"\\]|\\.)*)"', body)))


def size(fn):
    return int(re.search(rf"{fn}\(\) {{\s*int \[\] result = new int\[(\d+)\]", src).group(1))


def rle(name, fn, delta=0):
    p, out = packed(name), []
    for i in range(0, len(p), 2):
        out += [p[i + 1] + delta] * p[i]
    assert len(out) == size(fn), name
    return out


def pairs(name, fn):  # ZZ_ROWMAP: (high << 16) | low
    p = packed(name)
    out = [(p[i] << 16) | p[i + 1] for i in range(0, len(p), 2)]
    assert len(out) == size(fn), name
    return out


tables = [
    ("CMAP_TOP", "u16", rle("ZZ_CMAP_TOP", "zzUnpackcmap_top")),
    ("CMAP_BLOCKS", "u8", rle("ZZ_CMAP_BLOCKS", "zzUnpackcmap_blocks")),
    ("ACTION", "u8", rle("ZZ_ACTION", "zzUnpackAction")),
    ("ROWMAP", "u16", pairs("ZZ_ROWMAP", "zzUnpackRowMap")),
    ("TRANS", "i8", rle("ZZ_TRANS", "zzUnpackTrans", -1)),
    ("ATTRIBUTE", "u8", rle("ZZ_ATTRIBUTE", "zzUnpackAttribute")),
]
lines = [
    "// @generated by scripts/gen_standard_tokenizer_tables.py from Lucene 10.5.1",
    "// StandardTokenizerImpl.java (Apache-2.0). Do not edit.",
    "",
]
for name, ty, vals in tables:
    lo, hi = {"u8": (0, 255), "i8": (-128, 127), "u16": (0, 65535)}[ty]
    assert all(lo <= v <= hi for v in vals), name
    lines.append(f"pub(super) static {name}: [{ty}; {len(vals)}] = [")
    for i in range(0, len(vals), 32):
        lines.append("    " + ", ".join(map(str, vals[i:i + 32])) + ",")
    lines.append("];")
out = Path(__file__).parent.parent / "es-index/src/analysis/standard_tables.rs"
out.parent.mkdir(exist_ok=True)
out.write_text("\n".join(lines) + "\n")
print(out, [(n, len(v)) for n, _, v in tables])
